#!/bin/bash
EscapeRegexescape_re() {
  local s="$1"
  s="${s//\\/\\\\}"; s="${s//./\\.}"; s="${s//^/\\^}"; s="${s//\$/\\$}"
  s="${s//\*/\\*}"; s="${s//+/\\+}"; s="${s//\?/\\?}"
  s="${s//(/\\(}"; s="${s//)/\\)}"; s="${s//[/\\[}"; s="${s//]/\\]}"
  s="${s//\{ /\\{}"; s="${s//\}/\\}}"; s="${s//|/\\|}"
  printf '%s' "$s"
}

